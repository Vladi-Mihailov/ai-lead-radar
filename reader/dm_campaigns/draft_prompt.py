def _items_block(items) -> str:
    lines = []
    for item in items:
        note = f" [{item.note}]" if item.note else ""
        # Возраст сообщения ("N мин назад") модели не передаётся: он устареет,
        # пока оператор проверяет черновик (см. правило в SYSTEM_PROMPT).
        lines.append(f"{item.ref} | {item.chat} | {item.time_tbilisi} | {item.author}{note}: {item.text}")
    return "\n".join(lines) if lines else "нет"


def _reply_target_hint(context: DraftContext) -> str | None:
    """Детерминированная подсказка о роли: на чьё сообщение отвечает USER
    (ближайшее звено цепочки ответов — последний R)."""
    replies = [item for item in context.discussion if item.ref.startswith("R")]
    if not replies:
        return None
    target = replies[-1]
    if target.author == "USER":
        return f"USER продолжает своё собственное сообщение ({target.ref})."
    return (f"USER отвечает на сообщение ДРУГОГО участника ({target.author}, {target.ref}). По умолчанию это "
            "ANSWER/ADVICE/OPINION: лид — только если USER явно пишет о СВОЕЙ проблеме или задаёт СВОЙ вопрос, "
            "а не уточняет ситуацию того участника.")


def reply_to_other(context: DraftContext) -> bool:
    """USER отвечает на сообщение ДРУГОГО участника (ближайшее звено цепочки)."""
    replies = [item for item in context.discussion if item.ref.startswith("R")]
    return bool(replies) and replies[-1].author != "USER"


def build_classification_text(outreach: DmOutreach, context: DraftContext) -> str:
    """Вход шага 1: только сообщение и его контекст — без фактов кампании и
    ресурсов (классификатор не отвечает, а решает, нужен ли ответ вообще)."""
    sections = [
        f"SOURCE GROUP\n{outreach.source_chat_title or outreach.source_chat_identifier or 'группа'}",
        f"ORIGINAL MESSAGE (USER)\n{outreach.source_text[:2000]}",
        f"DISCUSSION CONTEXT\n{_items_block(context.discussion)}",
        f"REPLY TARGET\n{_reply_target_hint(context) or 'USER ни на что не отвечает (самостоятельное сообщение).'}",
    ]
    return "\n\n".join(sections)


def build_user_text(
    outreach: DmOutreach, campaign: DmCampaign, context: DraftContext,
    *, allowed_resources: tuple[str, ...] | None = None, border_policy: BorderPolicy | None = None,
    sender: SenderPersona | None = None, sender_known: bool = False,
) -> str:
    """allowed_resources — уже отобранные по стране группы и смыслу
    вопроса (см. reader/dm_campaigns/resources.py); None — ресурсы кампании."""
    items = campaign.resources if allowed_resources is None else allowed_resources
    lines = [f"{r} — {RESOURCE_HINTS[r]}" if r in RESOURCE_HINTS else r for r in items]
    resources = "\n".join(lines) if lines else "нет (ничего не рекламировать)"
    discussion = context.discussion
    if campaign.key == "border_queue":
        # Генератору border_queue — только обсуждение по теме проезда (или по
        # соседней теме, о которой спросил сам USER); цепочка ответов R — всегда.
        asked = side_topics(outreach.source_text)
        discussion = [i for i in discussion if i.ref.startswith("R") or not (side_topics(i.text) - asked)
                      or border_evidence_relevant(i.text, asked)]
        if border_policy is not None and border_policy.checkpoints:
            # и без сообщений о других КПП (вопрос о Ларсе — не про Сарпи/Вале)
            discussion = [i for i in discussion if i.ref.startswith("R")
                          or not (checkpoints_in(i.text) - border_policy.checkpoints)]
        resources = "не упоминай ресурсы — система добавит их сама"
    elif campaign.key == "fuel" and border_policy is not None and border_policy.cta:
        resources = "не упоминай ресурсы — система добавит их сама"
    sections = [
        f"CAMPAIGN\n{campaign.title} ({campaign.key})",
        f"CAMPAIGN RULES\n{_CAMPAIGN_RULES.get(campaign.key, 'нет')}",
        f"CAMPAIGN GUIDELINE (указание менеджера, не готовый текст)\n{campaign.ai_guideline or 'нет'}",
        f"ALLOWED PROMOTED RESOURCES\n{resources}",
        f"SOURCE GROUP\n{outreach.source_chat_title or outreach.source_chat_identifier or 'группа'}",
        f"ORIGINAL MESSAGE (USER)\n{outreach.source_text[:2000]}",
        f"DISCUSSION CONTEXT\n{_items_block(discussion)}",
    ]
    reply_hint = _reply_target_hint(context) if campaign.key in EXPERT_CAMPAIGNS else None
    if reply_hint:
        sections.append(f"REPLY TARGET\n{reply_hint}")
    if border_policy is not None and border_policy.kind == "border_queue":
        titles = ", ".join(CHECKPOINT_TITLES[c] for c in sorted(border_policy.checkpoints)) or "не указан"
        signals = ", ".join(border_policy.negative_signals) or "нет"
        sections.append(f"REQUESTED CHECKPOINT\n{titles}")
        sections.append(f"BORDER SIGNALS\nnegative_signals: {signals}")
    if context.fresh_context_used:
        meta = context.metadata
        sections.append(f"FRESH EVIDENCE\n{_items_block(context.evidence)}")
        sections.append(
            "EVIDENCE METADATA\n"
            f"n_messages={meta.n_messages}\n"
            f"n_distinct_senders={meta.n_distinct_senders}\n"
            "все сообщения выше — свежие (только для твоей оценки; время в тексте не упоминай)"
        )
    else:
        sections.append("FRESH EVIDENCE\nне используется для этой кампании")
    follow_up = (
        f"включён\nFOLLOW-UP GUIDELINE\n{campaign.follow_up_guideline or 'нет'}"
        if campaign.follow_up_enabled else "выключен (follow_up_message = null)"
    )
    sections.append(f"FOLLOW-UP\n{follow_up}")
    if sender is not None or sender_known:
        sections.append(sender_block(sender))
    return "\n\n".join(sections)


@dataclass(frozen=True)
class SenderPersona:
    """Ожидаемый отправитель черновика (первый по текущему порядку выбора);
    при отправке он может смениться (доступ к источнику, лимиты, блокировки)."""
    username: str
    gender: str | None  # "male" / "female" / None — неизвестно


_NEUTRAL_RULE = (
    "Prefer gender-neutral phrasing where natural, because delivery may fall back to another sender "
    "(«могу подсказать», «рекомендую», «обычно проверяю», «можно оформить» instead of «пользовался», "
    "«ездил», «покупал»)."
)


def sender_block(sender: SenderPersona | None) -> str:
    if sender is None or sender.gender not in ("male", "female"):
        return (
            "SENDER\nThe sender's gender is unknown. Do not use gendered first-person past-tense forms in "
            "Russian (оформлял/оформляла, проверял/проверяла, ездил/ездила, покупал/покупала): rephrase "
            f"gender-neutrally. {_NEUTRAL_RULE}"
        )
    forms = ("я оформляла, я проверяла, я ездила" if sender.gender == "female"
             else "я оформлял, я проверял, я ездил")
    return (
        f"SENDER\nThe reply will be sent from {sender.username}.\nSender gender: {sender.gender}.\n"
        "When speaking in the first person in Russian, use grammatical forms matching the sender "
        f"({forms}). {_NEUTRAL_RULE}"
    )
