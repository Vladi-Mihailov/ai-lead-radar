"""Извлечение российских автомобильных госномеров (формат A111AA111 —
буква, 3 цифры, 2 буквы, регион 2 или 3 цифры) из текста сообщения.

Общая функция для reader/core/pipeline.py (Pipeline, по новым сообщениям)
и reader/users/history_sync.py (sync_users.py, по истории/backfill) — тот
же архитектурный путь, что и reader/users/keyword_matches.py.unique_keywords()
для keywords, но независимая от совпадения сценария: госномер ищется в
ЛЮБОМ сообщении с известным отправителем, а не только в тех, что совпали
по keyword (см. вызывающий код).
"""

import re

# Допустимые буквы российского госномера — только они, а не любые буквы
# алфавита (см. задачу): кириллица и её латинский аналог по внешнему виду
# (ГОСТ Р 50577) — единственные буквы, которые Telegram-пользователь мог
# ввести, набирая номер и кириллицей, и латиницей, и вперемешку.
_CYRILLIC_TO_LATIN = {
    "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H",
    "О": "O", "Р": "P", "С": "C", "Т": "T", "У": "Y", "Х": "X",
}

_LETTERS = "".join(_CYRILLIC_TO_LATIN) + "".join(_CYRILLIC_TO_LATIN.values())
_LETTER_CLASS = f"[{_LETTERS}{_LETTERS.lower()}]"

# Разделитель между группами (буква/цифры/буквы/цифры) — пробел(ы) и/или
# дефис(ы), в любом количестве, включая полное отсутствие (см. примеры:
# "А111АА111", "А 111 АА 77", "А-111-АА-197"). Внутри самих групп
# (3 цифры, 2 буквы, регион) разделителей нет — только слитно.
_SEP = r"[\s-]*"

# \b на обеих границах — не позволяет извлечь номер как подстроку более
# длинной буквенно-цифровой последовательности (см. задачу): \b в Python
# re учитывает и кириллицу как словообразующие символы, поэтому "лишняя"
# буква/цифра сразу перед или сразу после совпадения (без разделителя)
# блокирует весь матч на этой позиции. Регион — ровно 2 или 3 цифры:
# если сразу после (без разделителя) идёт ещё одна цифра, \b на правой
# границе не выполняется ни для 2, ни для 3 цифр — совпадения не будет
# (см. негативный тест A123AB1234).
_PLATE_RE = re.compile(
    rf"\b{_LETTER_CLASS}{_SEP}\d{{3}}{_SEP}{_LETTER_CLASS}{{2}}{_SEP}\d{{2,3}}\b"
)


def _normalize_plate(raw: str) -> str:
    """А111АА111 -> A111AA111: убирает пробелы/дефисы, переводит в
    верхний регистр и заменяет кириллические буквы на латинские аналоги —
    цифры и уже латинские буквы не трогает."""
    cleaned = re.sub(r"[\s-]", "", raw).upper()
    return "".join(_CYRILLIC_TO_LATIN.get(ch, ch) for ch in cleaned)


def extract_car_numbers(text: str) -> list[str]:
    """Уникальные нормализованные госномера, упомянутые в text —
    кириллица/латиница/смешанное написание одного и того же номера
    считаются одним значением (нормализация ДО дедупликации). Порядок —
    сортированный, а не порядок появления (в отличие от unique_keywords):
    для car_numbers важнее детерминированность хранения одного
    пользователя (см. UserRepository.add_car_numbers), а не порядок, в
    котором номера упоминались."""
    if not text:
        return []
    found = {_normalize_plate(match.group(0)) for match in _PLATE_RE.finditer(text)}
    return sorted(found)
