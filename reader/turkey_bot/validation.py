"""Валидация гос. номера для GIB-запроса.

НАМЕРЕННО ЛЁГКАЯ проверка, а не полная грамматика турецких номеров
(2-значный код региона 01-81 + 1-3 буквы + 2-4 цифры, разные варианты для
старого/нового формата, дипломатических и т.п.) — см. design report Stage
2/3: тот же принцип "не гадать схему", применённый здесь к формату
номера: реальные граничные случаи не изучались вживую, а сам GIB — куда
более надёжный и уже проверенный вживую (см. design report Stage 2)
арбитр того, валиден ли номер, чем регэксп, угадывающий полную грамматику.
Эта функция отсеивает только заведомый мусор (пусто, слишком
длинно/коротко, не латиница/цифры) — не более."""

import re

_NORMALIZED_RE = re.compile(r"^[A-Z0-9]{5,8}$")


def normalize_plate(raw: str) -> str | None:
    """None — заведомо не похоже на номер, вызывающий код должен попросить
    ввести его снова, не отправляя запрос к GIB вовсе. Иначе — нормализованная
    строка (без пробелов, верхний регистр), которую можно передать в
    GibSession.submit(plate=...) как есть."""
    candidate = raw.strip().upper().replace(" ", "").replace("-", "")
    if not _NORMALIZED_RE.fullmatch(candidate):
        return None
    return candidate
