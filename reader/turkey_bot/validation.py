"""Валидация гос. номера для GIB-запроса.

НАМЕРЕННО ЛЁГКАЯ проверка, а не полная грамматика турецких/российских
номеров — см. design report Stage 2/3: тот же принцип "не гадать схему",
применённый здесь к формату номера: реальные граничные случаи не
изучались вживую, а сам GIB — куда более надёжный и уже проверенный
вживую (см. design report Stage 2, а также реальный успешный запрос с
российским номером A123AA123, вернувший легитимный no_debt) арбитр того,
валиден ли номер, чем регэксп, угадывающий полную грамматику. Эта функция
отсеивает только заведомый мусор (пусто, слишком длинно/коротко, не
буквы/цифры) — не более.

Целевая аудитория бота — в первую очередь русскоязычные водители с
российскими номерами (см. задачу), поэтому здесь ЖЕ нормализуются
кириллические буквы, визуально совпадающие с буквами на российских гос.
номерах (А В Е К М Н О Р С Т У Х), к их латинским аналогам ДО отправки в
GIB (см. GibSession.submit) — GIB принимает только латиницу. Только ЭТИ
12 букв — не произвольная кириллица (см. задачу: "Do NOT convert
arbitrary Cyrillic letters")."""

import re

# Визуальное соответствие кириллических букв на российских гос. номерах их
# латинским аналогам (см. задачу) — .upper() уже применён к строке до
# .translate(), поэтому здесь достаточно только заглавных кириллических
# ключей.
_CYRILLIC_TO_LATIN = str.maketrans(
    {
        "А": "A",
        "В": "B",
        "Е": "E",
        "К": "K",
        "М": "M",
        "Н": "H",
        "О": "O",
        "Р": "P",
        "С": "C",
        "Т": "T",
        "У": "Y",
        "Х": "X",
    }
)

# Верхняя граница увеличена с 8 до 9 — российский номер с 3-значным кодом
# региона (например, A123AA123) даёт 9 символов после нормализации, длиннее
# турецкого формата (см. задачу: реальный успешный тест с этим номером).
_NORMALIZED_RE = re.compile(r"^[A-Z0-9]{5,9}$")


def normalize_plate(raw: str) -> str | None:
    """None — заведомо не похоже на номер, вызывающий код должен попросить
    ввести его снова, не отправляя запрос к GIB вовсе. Иначе — нормализованная
    строка (без пробелов, верхний регистр, кириллица российских номеров
    приведена к латинице), которую можно передать в GibSession.submit(
    plate=...) как есть.

    Буква, отсутствующая среди поддерживаемых 12 (например, Б/Г/Д/Ж/...),
    остаётся кириллической после .translate() и поэтому не проходит
    _NORMALIZED_RE (только [A-Z0-9]) — номер с такой буквой корректно
    отклоняется, а не "тихо" пропускается с мусором внутри."""
    candidate = raw.strip().upper().replace(" ", "").replace("-", "")
    candidate = candidate.translate(_CYRILLIC_TO_LATIN)
    if not _NORMALIZED_RE.fullmatch(candidate):
        return None
    return candidate
